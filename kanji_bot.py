async def _render_card(call: CallbackQuery, kid: int, flt: str, page: int) -> None:
    """Отрисовывает карточку иероглифа без мутации frozen-объекта CallbackQuery."""
    uid = call.from_user.id
    k = KANJI_DB.get(kid)
    if not k:
        await call.answer("Иероглиф не найден.")
        return

    items = filter_kanji_by_pool(uid, flt)
    ids = [x.id for x in items]
    pos = ids.index(kid) if kid in ids else -1

    is_fav = db.is_favorite(uid, kid)
    u_stat = db.get_kanji_stat(uid, kid)
    text = format_kanji_card(k, is_fav, u_stat)

