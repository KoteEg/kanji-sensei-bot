def progress_bar(current: int, total: int, length: int = 10) -> str:
    """Аккуратная шкала прогресса."""
    if total <= 0:
        return "▱" * length
    filled = max(0, min(length, int(round((current / total) * length))))
    return "▰" * filled + "▱" * (length - filled)


def weighted_sample_without_replacement(
    items: List[KanjiEntry], weights_map: Dict[int, float], k: int
) -> List[KanjiEntry]:
    pool = list(items)
    selected: List[KanjiEntry] = []
    for _ in range(min(k, len(pool))):
        w_list = [weights_map.get(item.id, 1.0) for item in pool]
        chosen = random.choices(pool, weights=w_list, k=1)[0]
        selected.append(chosen)
        pool.remove(chosen)
    return selected


def filter_kanji_by_pool(user_id: int, pool_code: str) -> List[KanjiEntry]:
    """Возвращает список кандзи по выбранному пулу: N5, N4, ALL, HARD, FAV."""
    if pool_code in {"N5", "N4"}:
        return [k for k in KANJI_LIST if k.level == pool_code]
    if pool_code == "HARD":
        ids = db.get_hard_ids(user_id)
        return [KANJI_DB[i] for i in ids if i in KANJI_DB]
    if pool_code == "FAV":
        ids = db.get_favorite_ids(user_id)
        return [KANJI_DB[i] for i in ids if i in KANJI_DB]
    return list(KANJI_LIST)


def _format_explanation_radicals(radicals_text: str) -> str:
    """Красиво оформляет ключи и историю для пояснения в тесте."""
    rad_part, story_part = split_radicals_and_story(radicals_text)
    if story_part:
        return (
            f"🧩 <b>{html.escape(rad_part)}</b>\n"
            f"<blockquote>📜 {html.escape(story_part)}</blockquote>"
        )
    return f"<blockquote>🧩 {html.escape(rad_part)}</blockquote>"


def build_question(
    kanji: KanjiEntry,
    mode: str,
    read_type: str,
    distractor_pool: List[KanjiEntry],
) -> Optional[dict]:
    """Генерирует вопрос (4 варианта или ручной ввод иероглифа)."""
    actual_mode = mode
    if mode == "jlpt":
        candidates = ["mean"]
        if kanji.onyomi != "—" or kanji.kunyomi != "—":
            candidates.append("read")
        if kanji.words:
            candidates.append("word")
        actual_mode = random.choice(candidates)

    other_kanji = [k for k in distractor_pool if k.id != kanji.id]
    if len(other_kanji) < 3:
        other_kanji = [k for k in KANJI_LIST if k.id != kanji.id]

    lvl_dot = "🟢" if kanji.level == "N5" else "🔵"

    # --- Режим 1: Чтения (Онъёми / Кунъёми) ---
    if actual_mode == "read":
        if read_type == "ON" and kanji.onyomi != "—":
            ask_on = True
        elif read_type == "KUN" and kanji.kunyomi != "—":
            ask_on = False
        else:
            if kanji.onyomi != "—" and kanji.kunyomi != "—":
                ask_on = random.choice([True, False])
            elif kanji.onyomi != "—":
                ask_on = True
            elif kanji.kunyomi != "—":
                ask_on = False
            else:
                return None

        correct_ans = kanji.onyomi if ask_on else kanji.kunyomi
        type_label = "Онъёми (音読み)" if ask_on else "Кунъёми (訓読み)"

        distractors = []
        random.shuffle(other_kanji)
        for ok in other_kanji:
            cand = ok.onyomi if ask_on else ok.kunyomi
            if cand != "—" and cand != correct_ans and cand not in distractors:
                distractors.append(cand)
            if len(distractors) == 3:
                break
        if len(distractors) < 3:
            return None

        options = distractors + [correct_ans]
        random.shuffle(options)

        prompt_html = (
            f"{lvl_dot} <b>JLPT {kanji.level}</b>  ·  🗣️ <code>問題 1 · Чтение</code>\n"
            f"{DIVIDER}\n\n"
            f"　　　<b>【 {kanji.char} 】</b>\n\n"
            f"Выберите правильное <b>{type_label}</b>:"
        )
        explanation_html = (
            f"🏮 <b>【 {kanji.char} 】</b> — <b>{html.escape(kanji.meaning)}</b>\n"
            f"🗣️ Онъёми: <code>{html.escape(kanji.onyomi)}</code>\n"
            f"🗣️ Кунъёми: <code>{html.escape(kanji.kunyomi)}</code>\n\n"
            f"{_format_explanation_radicals(kanji.radicals)}"
        )
        return {
            "kanji_id": kanji.id,
            "q_type": "read",
            "prompt_html": prompt_html,
            "options": options,
            "correct_idx": options.index(correct_ans),
            "explanation_html": explanation_html,
        }

    # --- Режим 2: Значение ---
    if actual_mode == "mean":
        correct_ans = kanji.meaning
        distractors = []
        random.shuffle(other_kanji)
        for ok in other_kanji:
            if ok.meaning != correct_ans and ok.meaning not in distractors:
                distractors.append(ok.meaning)
            if len(distractors) == 3:
                break

        options = distractors + [correct_ans]
        random.shuffle(options)

        prompt_html = (
            f"{lvl_dot} <b>JLPT {kanji.level}</b>  ·  💡 <code>問題 2 · Значение</code>\n"
            f"{DIVIDER}\n\n"
            f"　　　<b>【 {kanji.char} 】</b>\n\n"
            f"Что означает этот иероглиф?"
        )
        explanation_html = (
            f"🏮 <b>【 {kanji.char} 】</b> — <b>{html.escape(kanji.meaning)}</b>\n"
            f"🗣️ Он: <code>{html.escape(kanji.onyomi)}</code>  ·  "
            f"Кун: <code>{html.escape(kanji.kunyomi)}</code>\n\n"
            f"{_format_explanation_radicals(kanji.radicals)}"
        )
        return {
            "kanji_id": kanji.id,
            "q_type": "mean",
            "prompt_html": prompt_html,
            "options": options,
            "correct_idx": options.index(correct_ans),
            "explanation_html": explanation_html,
        }

    # --- Режим 3: Кандзи в слове (с переводом и пометкой уровня) ---
    if actual_mode == "word":
        if not kanji.words:
            return None
        word_jp, word_read, word_tr = random.choice(kanji.words)
        masked_word = word_jp.replace(kanji.char, "＿", 1)
        lvl_badge = get_word_level_badge(word_jp)

        correct_ans = word_jp
        distractors = []
        random.shuffle(other_kanji)
        for ok in other_kanji:
            fake_word = word_jp.replace(kanji.char, ok.char, 1)
            if fake_word != correct_ans and fake_word not in distractors:
                distractors.append(fake_word)
            if len(distractors) == 3:
                break
        if len(distractors) < 3:
            return None

        options = distractors + [correct_ans]
        random.shuffle(options)

        prompt_html = (
            f"{lvl_dot} <b>JLPT {kanji.level}</b>  ·  ✍️ <code>問題 3 · 表記</code>\n"
            f"{DIVIDER}\n\n"
            f"📝 Слово: <b>{html.escape(masked_word)}</b>  (<code>{html.escape(word_read)}</code>){lvl_badge}\n"
            f"💬 Перевод: <i>«{html.escape(word_tr)}»</i>\n\n"
            f"Выберите правильный вариант написания:"
        )
        explanation_html = (
            f"✨ <b>{html.escape(word_jp)}</b> (<code>{html.escape(word_read)}</code>){lvl_badge} — {html.escape(word_tr)}\n\n"
            f"🏮 Кандзи: <b>【 {kanji.char} 】</b> — {html.escape(kanji.meaning)}\n\n"
            f"{_format_explanation_radicals(kanji.radicals)}"
        )
        return {
            "kanji_id": kanji.id,
            "q_type": "word",
            "prompt_html": prompt_html,
            "options": options,
            "correct_idx": options.index(correct_ans),
            "explanation_html": explanation_html,
        }

    # --- Режим 4: Ручной ввод иероглифа ---
    if actual_mode == "write":
        example_block = ""
        example_word = ""
        if kanji.words:
            w_jp, w_read, w_tr = random.choice(kanji.words)
            masked = w_jp.replace(kanji.char, "＿", 1)
            lvl_badge = get_word_level_badge(w_jp)
            example_word = w_jp
            example_block = (
                f"\n📝 Пример: <b>{html.escape(masked)}</b> "
                f"(<code>{html.escape(w_read)}</code>){lvl_badge} — <i>{html.escape(w_tr)}</i>\n"
            )

        rad_part, _ = split_radicals_and_story(kanji.radicals)

        prompt_html = (
            f"{lvl_dot} <b>JLPT {kanji.level}</b>  ·  ⌨️ <code>Ручной ввод кандзи</code>\n"
            f"{DIVIDER}\n\n"
            f"💡 Значение: <b>{html.escape(kanji.meaning)}</b>\n"
            f"🗣️ Онъёми: <code>{html.escape(kanji.onyomi)}</code>\n"
            f"🗣️ Кунъёми: <code>{html.escape(kanji.kunyomi)}</code>"
            f"{example_block}\n"
            f"✍️ <i>Отправь в чат подходящий иероглиф:</i>"
        )
        explanation_html = (
            f"🏮 <b>【 {kanji.char} 】</b> — <b>{html.escape(kanji.meaning)}</b>\n"
            f"🗣️ Он: <code>{html.escape(kanji.onyomi)}</code>  ·  "
            f"Кун: <code>{html.escape(kanji.kunyomi)}</code>\n\n"
            f"{_format_explanation_radicals(kanji.radicals)}"
        )
        return {
            "kanji_id": kanji.id,
            "q_type": "write",
            "expected_char": kanji.char,
            "example_word": example_word,
            "hint_text": rad_part,
            "prompt_html": prompt_html,
            "options": [],
            "correct_idx": -1,
            "explanation_html": explanation_html,
        }

    return None


def generate_quiz(
    user_id: int,
    mode: str,
    level: str,
    count: int,
    read_type: str,
    only_kanji_ids: Optional[List[int]] = None,
) -> List[dict]:
    pool = (
        [KANJI_DB[kid] for kid in only_kanji_ids if kid in KANJI_DB]
        if only_kanji_ids
        else filter_kanji_by_pool(user_id, level)
    )

    eligible: List[KanjiEntry] = []
    for k in pool:
        if mode == "read":
            if read_type == "ON" and k.onyomi == "—":
                continue
            if read_type == "KUN" and k.kunyomi == "—":
                continue
            if k.onyomi == "—" and k.kunyomi == "—":
                continue
        elif mode == "word" and not k.words:
            continue
        eligible.append(k)

    if not eligible:
        return []

    weights_map = db.get_weights(user_id)
    chosen = weighted_sample_without_replacement(eligible, weights_map, count)

    questions = []
    for k in chosen:
        q = build_question(k, mode, read_type, pool)
        if q:
            questions.append(q)
    return questions


