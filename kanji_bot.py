async def _render_question(message: Message, state: FSMContext) -> None:
    data = await state.get_data()
    questions = data["questions"]
    idx = data["idx"]
    total = len(questions)
    q = questions[idx]

    bar = progress_bar(idx, total, length=10)
    full_text = f"⏱ <b>Вопрос {idx + 1} из {total}</b>  <code>{bar}</code>\n\n" + q["prompt_html"]

    kb_rows = []
    max_len = max(len(opt) for opt in q["options"])

    if max_len <= 10:
        kb_rows.append([
            InlineKeyboardButton(text=q["options"][0], callback_data=f"ans:{idx}:0"),
            InlineKeyboardButton(text=q["options"][1], callback_data=f"ans:{idx}:1"),
        ])
        kb_rows.append([
            InlineKeyboardButton(text=q["options"][2], callback_data=f"ans:{idx}:2"),
            InlineKeyboardButton(text=q["options"][3], callback_data=f"ans:{idx}:3"),
        ])
    elif max_len <= 22:
        for i, opt in enumerate(q["options"]):
            kb_rows.append([InlineKeyboardButton(text=opt, callback_data=f"ans:{idx}:{i}")])
    else:
        num_icons = ["1️⃣", "2️⃣", "3️⃣", "4️⃣"]
        options_block = "\n".join(
            f"{num_icons[i]} {html.escape(opt)}" for i, opt in enumerate(q["options"])
        )
        full_text += f"\n\n{options_block}"
        kb_rows.append([
            InlineKeyboardButton(text=num_icons[i], callback_data=f"ans:{idx}:{i}")
            for i in range(4)
        ])

    kb_rows.append([InlineKeyboardButton(text="🚪 Завершить тест", callback_data="menu")])
    await safe_edit(message, full_text, reply_markup=InlineKeyboardMarkup(inline_keyboard=kb_rows))


@router.callback_query(BotStates.in_quiz, F.data.startswith("ans:"))
async def cb_answer(call: CallbackQuery, state: FSMContext) -> None:
    _, q_idx_str, opt_idx_str = call.data.split(":")
    q_idx = int(q_idx_str)
    opt_idx = int(opt_idx_str)

    data = await state.get_data()
    if q_idx != data.get("idx"):
        await call.answer("Вопрос уже пройден.")
        return

    questions = data["questions"]
    q = questions[q_idx]
    is_correct = opt_idx == q["correct_idx"]
    db.record_answer(call.from_user.id, q["kanji_id"], is_correct)

    score = data["score"] + (1 if is_correct else 0)
    wrong_ids: List[int] = list(data["wrong_ids"])
    if not is_correct and q["kanji_id"] not in wrong_ids:
        wrong_ids.append(q["kanji_id"])

    await state.update_data(score=score, wrong_ids=wrong_ids, idx=q_idx + 1)

    total = len(questions)
    bar = progress_bar(q_idx + 1, total, length=10)
    if is_correct:
        verdict = "✅ <b>Верно! Отлично!</b>"
        srs_note = ""
    else:
        verdict = f"❌ <b>Ошибка</b>  <i>(вы выбрали: {html.escape(q['options'][opt_idx])})</i>"
        srs_note = "\n\n🔥 <i>Этот иероглиф добавлен в приоритетное повторение.</i>"

    feedback_text = (
        f"⏱ <b>Вопрос {q_idx + 1} из {total}</b>  <code>{bar}</code>\n\n"
        f"{verdict}\n\n"
        f"{q['explanation_html']}"
        f"{srs_note}"
    )

    next_label = "➡️ Следующий вопрос" if (q_idx + 1) < total else "🏁 Показать итоги"
    kb = InlineKeyboardMarkup(
        inline_keyboard=[
            [InlineKeyboardButton(text=next_label, callback_data="next_q")],
            [InlineKeyboardButton(text="📖 Полная карточка кандзи", callback_data=f"qcard:{q['kanji_id']}")],
        ]
    )
    await safe_edit(call.message, feedback_text, reply_markup=kb)
    await call.answer("✅ Верно!" if is_correct else "❌ Неверно")


