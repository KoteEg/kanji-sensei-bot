class Database:
    """Хранение настроек пользователя, статистики и адаптивных весов (SRS)."""

    def __init__(self, path: str):
        self.path = path
        self._init_db()

    def _conn(self) -> sqlite3.Connection:
        conn = sqlite3.connect(self.path)
        conn.row_factory = sqlite3.Row
        return conn

    def _init_db(self) -> None:
        with self._conn() as conn:
            conn.executescript(
                """
                CREATE TABLE IF NOT EXISTS users (
                    user_id INTEGER PRIMARY KEY,
                    username TEXT,
                    pref_level TEXT DEFAULT 'ALL',
                    pref_count INTEGER DEFAULT 10,
                    pref_read_type TEXT DEFAULT 'MIX',
                    total_tests INTEGER DEFAULT 0,
                    total_answers INTEGER DEFAULT 0,
                    total_correct INTEGER DEFAULT 0,
                    streak_days INTEGER DEFAULT 0,
                    last_active_date TEXT
                );

                CREATE TABLE IF NOT EXISTS kanji_progress (
                    user_id INTEGER,
                    kanji_id INTEGER,
                    correct_count INTEGER DEFAULT 0,
                    wrong_count INTEGER DEFAULT 0,
                    weight REAL DEFAULT 1.0,
                    is_favorite INTEGER DEFAULT 0,
                    PRIMARY KEY (user_id, kanji_id)
                );
                """
            )

    def ensure_user(self, user_id: int, username: str = "") -> sqlite3.Row:
        with self._conn() as conn:
            row = conn.execute("SELECT * FROM users WHERE user_id = ?", (user_id,)).fetchone()
            if not row:
                today_str = date.today().isoformat()
                conn.execute(
                    """
                    INSERT INTO users (user_id, username, streak_days, last_active_date)
                    VALUES (?, ?, 1, ?)
                    """,
                    (user_id, username, today_str),
                )
                row = conn.execute("SELECT * FROM users WHERE user_id = ?", (user_id,)).fetchone()
            elif username and row["username"] != username:
                conn.execute("UPDATE users SET username = ? WHERE user_id = ?", (username, user_id))
            return row

    def set_pref(self, user_id: int, field: str, value) -> None:
        if field not in {"pref_level", "pref_count", "pref_read_type"}:
            return
        with self._conn() as conn:
            conn.execute(f"UPDATE users SET {field} = ? WHERE user_id = ?", (value, user_id))

    def update_streak(self, user_id: int) -> None:
        today = date.today()
        today_str = today.isoformat()
        with self._conn() as conn:
            row = conn.execute(
                "SELECT streak_days, last_active_date FROM users WHERE user_id = ?",
                (user_id,),
            ).fetchone()
            if not row or row["last_active_date"] == today_str:
                return
            streak = row["streak_days"] or 1
            if row["last_active_date"]:
                try:
                    last_d = date.fromisoformat(row["last_active_date"])
                    streak = streak + 1 if last_d == today - timedelta(days=1) else 1
                except ValueError:
                    streak = 1
            conn.execute(
                "UPDATE users SET streak_days = ?, last_active_date = ? WHERE user_id = ?",
                (streak, today_str, user_id),
            )

    def record_answer(self, user_id: int, kanji_id: int, is_correct: bool) -> None:
        with self._conn() as conn:
            row = conn.execute(
                "SELECT correct_count, wrong_count, weight FROM kanji_progress WHERE user_id = ? AND kanji_id = ?",
                (user_id, kanji_id),
            ).fetchone()
            if not row:
                correct_c = 1 if is_correct else 0
                wrong_c = 0 if is_correct else 1
                new_w = 0.8 if is_correct else 4.2
                conn.execute(
                    """
                    INSERT INTO kanji_progress (user_id, kanji_id, correct_count, wrong_count, weight)
                    VALUES (?, ?, ?, ?, ?)
                    """,
                    (user_id, kanji_id, correct_c, wrong_c, new_w),
                )
            else:
                correct_c = row["correct_count"] + (1 if is_correct else 0)
                wrong_c = row["wrong_count"] + (0 if is_correct else 1)
                old_w = row["weight"]
                new_w = (
                    max(0.5, round(old_w * 0.72, 2))
                    if is_correct
                    else min(25.0, round(old_w * 2.2 + 2.0, 2))
                )
                conn.execute(
                    """
                    UPDATE kanji_progress
                    SET correct_count = ?, wrong_count = ?, weight = ?
                    WHERE user_id = ? AND kanji_id = ?
                    """,
                    (correct_c, wrong_c, new_w, user_id, kanji_id),
                )

            conn.execute(
                """
                UPDATE users
                SET total_answers = total_answers + 1,
                    total_correct = total_correct + ?
                WHERE user_id = ?
                """,
                (1 if is_correct else 0, user_id),
            )

    def increment_tests(self, user_id: int) -> None:
        with self._conn() as conn:
            conn.execute("UPDATE users SET total_tests = total_tests + 1 WHERE user_id = ?", (user_id,))
        self.update_streak(user_id)

    def get_weights(self, user_id: int) -> Dict[int, float]:
        with self._conn() as conn:
            rows = conn.execute(
                "SELECT kanji_id, weight FROM kanji_progress WHERE user_id = ?", (user_id,)
            ).fetchall()
            return {r["kanji_id"]: r["weight"] for r in rows}

    def toggle_favorite(self, user_id: int, kanji_id: int) -> bool:
        with self._conn() as conn:
            row = conn.execute(
                "SELECT is_favorite FROM kanji_progress WHERE user_id = ? AND kanji_id = ?",
                (user_id, kanji_id),
            ).fetchone()
            if not row:
                conn.execute(
                    "INSERT INTO kanji_progress (user_id, kanji_id, is_favorite) VALUES (?, ?, 1)",
                    (user_id, kanji_id),
                )
                return True
            new_val = 0 if row["is_favorite"] else 1
            conn.execute(
                "UPDATE kanji_progress SET is_favorite = ? WHERE user_id = ? AND kanji_id = ?",
                (new_val, user_id, kanji_id),
            )
            return bool(new_val)

    def is_favorite(self, user_id: int, kanji_id: int) -> bool:
        with self._conn() as conn:
            row = conn.execute(
                "SELECT is_favorite FROM kanji_progress WHERE user_id = ? AND kanji_id = ?",
                (user_id, kanji_id),
            ).fetchone()
            return bool(row and row["is_favorite"])

    def get_favorite_ids(self, user_id: int) -> List[int]:
        with self._conn() as conn:
            rows = conn.execute(
                "SELECT kanji_id FROM kanji_progress WHERE user_id = ? AND is_favorite = 1 ORDER BY kanji_id",
                (user_id,),
            ).fetchall()
            return [r["kanji_id"] for r in rows]

    def get_hard_ids(self, user_id: int) -> List[int]:
        with self._conn() as conn:
            rows = conn.execute(
                """
                SELECT kanji_id FROM kanji_progress
                WHERE user_id = ? AND (wrong_count > 0 AND weight > 1.2)
                ORDER BY weight DESC, wrong_count DESC
                """,
                (user_id,),
            ).fetchall()
            return [r["kanji_id"] for r in rows]

    def get_user_stats(self, user_id: int) -> dict:
        user = self.ensure_user(user_id)
        with self._conn() as conn:
            learned_rows = conn.execute(
                "SELECT kanji_id, correct_count, wrong_count, weight, is_favorite FROM kanji_progress WHERE user_id = ?",
                (user_id,),
            ).fetchall()

        learned_n5 = 0
        learned_n4 = 0
        fav_count = 0
        hard_list = []
        for r in learned_rows:
            k = KANJI_DB.get(r["kanji_id"])
            if not k:
                continue
            if r["is_favorite"]:
                fav_count += 1
            if r["correct_count"] >= 1 and r["correct_count"] >= r["wrong_count"]:
                if k.level == "N5":
                    learned_n5 += 1
                else:
                    learned_n4 += 1
            if r["wrong_count"] > 0 and r["weight"] > 1.2:
                hard_list.append((k, r["wrong_count"], r["weight"]))

        hard_list.sort(key=lambda x: (x[2], x[1]), reverse=True)
        total_n5 = sum(1 for k in KANJI_LIST if k.level == "N5")
        total_n4 = sum(1 for k in KANJI_LIST if k.level == "N4")

        return {
            "total_tests": user["total_tests"],
            "total_answers": user["total_answers"],
            "total_correct": user["total_correct"],
            "streak": user["streak_days"],
            "learned_n5": learned_n5,
            "total_n5": total_n5,
            "learned_n4": learned_n4,
            "total_n4": total_n4,
            "fav_count": fav_count,
            "hard_count": len(hard_list),
            "hard_top": hard_list[:6],
        }

    def get_kanji_stat(self, user_id: int, kanji_id: int) -> Tuple[int, int, float]:
        """Возвращает (верно, ошибок, вес) по конкретному иероглифу."""
        with self._conn() as conn:
            row = conn.execute(
                "SELECT correct_count, wrong_count, weight FROM kanji_progress WHERE user_id = ? AND kanji_id = ?",
                (user_id, kanji_id),
            ).fetchone()
            if not row:
                return 0, 0, 1.0
            return row["correct_count"], row["wrong_count"], row["weight"]

    def reset_user_progress(self, user_id: int) -> None:
        with self._conn() as conn:
            conn.execute("DELETE FROM kanji_progress WHERE user_id = ?", (user_id,))
            conn.execute(
                "UPDATE users SET total_tests = 0, total_answers = 0, total_correct = 0, streak_days = 1 WHERE user_id = ?",
                (user_id,),
            )


