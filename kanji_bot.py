async def _perform_search(message: Message, raw_query: str) -> None:
    """Ищет иероглифы по значению, чтениям, символу и примерам слов."""
    query = raw_query.strip().lower()
    if not query:
        await message.answer("Напиши запрос для поиска или нажми /menu.")
        return

    uid = message.from_user.id
    found = []
    for k in KANJI_LIST:
        if (
            query in k.char.lower()
            or query in k.meaning.lower()
            or query in k.onyomi.lower()
            or query in k.kunyomi.lower()
            or any(query in w.lower() or query in r.lower() or query in t.lower() for w, r, t in k.words)
        ):
            found.append(k)
        if len(found) >= 10:
            break

    if not found:
        kb = InlineKeyboardMarkup(
            inline_keyboard=[
                [InlineKeyboardButton(text="🔍 Искать снова", callback_data="search")],
                [InlineKeyboardButton(text="🏠 Главное меню", callback_data="menu")],
            ]
        )
        await message.answer(f"😔 По запросу «{html.escape(raw_query.strip())}» ничего не найдено.", reply_markup=kb)
        return

    if len(found) == 1:
        k = found[0]
        is_fav = db.is_favorite(uid, k.id)
        u_stat = db.get_kanji_stat(uid, k.id)
        await message.answer(
            format_kanji_card(k, is_fav, u_stat),
            reply_markup=_search_card_kb(uid, k.id),
            disable_web_page_preview=True,
        )
        return

    kb_rows = [
        [InlineKeyboardButton(text=f"🏮 {k.char} — {k.meaning[:24]} ({k.level})", callback_data=f"card:{k.id}:ALL:0")]
        for k in found
    ]
    kb_rows.append([
        InlineKeyboardButton(text="🔍 Новый поиск", callback_data="search"),
        InlineKeyboardButton(text="🏠 Меню", callback_data="menu"),
    ])
    await message.answer(
        f"🔍 <b>Найдено по запросу «{html.escape(raw_query.strip())}»</b> ({len(found)}):",
        reply_markup=InlineKeyboardMarkup(inline_keyboard=kb_rows),
    )


