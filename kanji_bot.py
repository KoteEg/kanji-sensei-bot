def get_word_level_badge(word: str) -> str:
    """Возвращает HTML-бейдж уровня, если слово выше N5–N4."""
    lvl = WORD_HIGHER_LEVELS.get(word)
    if not lvl:
        return ""
    return f" <code>[{lvl}]</code>"


def split_radicals_and_story(radicals_text: str) -> Tuple[str, str]:
    """Разделяет строку на часть с ключами и историю/мнемонику."""
    text = radicals_text.strip()
    if ". " in text:
        rad_part, story_part = text.split(". ", 1)
        return rad_part.strip().rstrip("."), story_part.strip()
    return text, ""


