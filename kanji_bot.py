async def _start_health_server() -> Optional[web.AppRunner]:
    if PORT <= 0:
        return None
    app = web.Application()

    async def health(_request: web.Request) -> web.Response:
        return web.Response(text=f"Kanji Sensei Bot is alive. Kanji: {len(KANJI_LIST)}")

    app.router.add_get("/", health)
    app.router.add_get("/health", health)
    runner = web.AppRunner(app)
    await runner.setup()
    site = web.TCPSite(runner, "0.0.0.0", PORT)
    await site.start()
    logger.info("HTTP health-check сервер запущен на порту %d", PORT)
    return runner


def _detect_proxy() -> str:
    if PROXY_URL:
        return PROXY_URL
    proxies = urllib.request.getproxies()
    raw = proxies.get("https") or proxies.get("http") or ""
    if raw and "://" not in raw:
        raw = "http://" + raw
    return raw


async def main() -> None:
    if not BOT_TOKEN:
        logger.error("Не задана переменная окружения BOT_TOKEN! Укажите новый токен от @BotFather.")
        sys.exit(1)

    proxy = _detect_proxy()
    if proxy:
        logger.info("Обнаружен прокси: %s", proxy)
        session = AiohttpSession(proxy=proxy)
    else:
        session = AiohttpSession()
    session._connector_init["family"] = socket.AF_INET

    bot = Bot(
        token=BOT_TOKEN,
        session=session,
        default=DefaultBotProperties(parse_mode=ParseMode.HTML),
    )
    dp = Dispatcher(storage=MemoryStorage())
    dp.include_router(router)

    health_runner = await _start_health_server()
    logger.info("Запуск Kanji Sensei Bot... Встроено иероглифов: %d", len(KANJI_LIST))

    try:
        await bot.delete_webhook(drop_pending_updates=True)
        await dp.start_polling(bot)
    finally:
        await bot.session.close()
        if health_runner:
            await health_runner.cleanup()


if __name__ == "__main__":
    try:
        asyncio.run(main())
    except (KeyboardInterrupt, SystemExit):
        logger.info("Бот остановлен.")
