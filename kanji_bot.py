async def _finish_quiz(message: Message, user_id: int, state: FSMContext) -> None:
    data = await state.get_data()
    total = len(data["questions"])
    score = data["score"]
    wrong_ids: List[int] = data["wrong_ids"]
    mode = data["mode"]
    pct = int(round((score / total) * 100)) if total else 0

    db.increment_tests(user_id)

    if pct >= 90:
        grade = "🏆 <b>合格 (Гокаку) — Сдано с отличием!</b>"
    elif pct >= 60:
        grade = "🌸 <b>合格 (Гокаку) — Экзамен сдан!</b>"
    else:
        grade = "🌧 <b>不合格 (Фугокаку) — Нужно ещё потренироваться</b>"

    wrong_block = ""
    if wrong_ids:
        chars = "  ·  ".join(
            f"<b>{KANJI_DB[kid].char}</b> ({html.escape(KANJI_DB[kid].meaning.split(',')[0])})"
            for kid in wrong_ids
            if kid in KANJI_DB
        )
        wrong_block = f"\n\n🔥 <b>На повторение ({len(wrong_ids)}):</b>\n{chars}"

    summary = (
        f"🎌 <b>Итоги тренировки</b> · {MODE_TITLES.get(mode, mode)}\n"
        f"{DIVIDER}\n\n"
        f"{grade}\n\n"
        f"🎯 Результат: <b>{score} из {total}</b> ({pct}%)\n"
        f"<code>{progress_bar(score, total, 12)}</code>"
        f"{wrong_block}"
    )

    kb_rows = []
    if wrong_ids:
        kb_rows.append([InlineKeyboardButton(text="🔁 Работа над ошибками", callback_data="retry_err")])
    kb_rows.append([
        InlineKeyboardButton(text="🔄 Ещё раз", callback_data=f"go:{mode}"),
        InlineKeyboardButton(text="⚙️ Настройки", callback_data=f"setup:{mode}"),
    ])
    kb_rows.append([InlineKeyboardButton(text="🏠 Главное меню", callback_data="menu")])

    await state.set_state(None)
    await safe_edit(message, summary, reply_markup=InlineKeyboardMarkup(inline_keyboard=kb_rows))


