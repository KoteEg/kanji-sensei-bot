def load_kanji_database() -> Dict[int, KanjiEntry]:
    """Разбирает встроенную чистую базу из 305 кандзи."""
    result: Dict[int, KanjiEntry] = {}
    for line in KANJI_DATA_RAW.strip().splitlines():
        line = line.strip()
        if not line:
            continue
        parts = line.split("|")
        if len(parts) < 8:
            continue
        kid = int(parts[0])
        level = parts[1]
        char = parts[2]
        meaning = parts[3]
        onyomi = parts[4]
        kunyomi = parts[5]
        radicals = parts[6]
        words: List[Tuple[str, str, str]] = []
        for item in parts[7].split(";"):
            wp = item.split(":", 2)
            if len(wp) == 3:
                words.append((wp[0].strip(), wp[1].strip(), wp[2].strip()))
        result[kid] = KanjiEntry(
            id=kid,
            level=level,
            char=char,
            meaning=meaning,
            onyomi=onyomi,
            kunyomi=kunyomi,
            radicals=radicals,
            words=words,
        )
    return result


KANJI_DB: Dict[int, KanjiEntry] = load_kanji_database()
KANJI_LIST: List[KanjiEntry] = sorted(KANJI_DB.values(), key=lambda x: x.id)


