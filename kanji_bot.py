@router.message(BotStates.waiting_search)
async def msg_search_process(message: Message, state: FSMContext) -> None:
    query = (message.text or "").strip().lower()
    if not query:
        await message.answer("Напиши запрос для поиска или нажми /menu.")
        return

    found = []
    for k in KANJI_LIST:
        if (
            query in k.char.lower()
            or query in k.meaning.lower()
            or query in k.onyomi.lower()
            or query in k.kunyomi.lower()
            or any(query in w.lower() or query in r.lower() or query in t.lower() for w, r, t in k.words)
        ):
            found.append(k)
        if len(found) >= 10:
            break

    await state.clear()

    if not found:
        kb = InlineKeyboardMarkup(
            inline_keyboard=[
                [InlineKeyboardButton(text="🔍 Искать снова", callback_data="search")],
                [InlineKeyboardButton(text="🏠 Главное меню", callback_data="menu")],
            ]
        )
        await message.answer(f"😔 По запросу «{html.escape(query)}» ничего не найдено.", reply_markup=kb)
        return

    if len(found) == 1:
        k = found[0]
        is_fav = db.is_favorite(message.from_user.id, k.id)
        u_stat = db.get_kanji_stat(message.from_user.id, k.id)
        kb = InlineKeyboardMarkup(
            inline_keyboard=[
                [InlineKeyboardButton(text="🔍 Новый поиск", callback_data="search")],
                [InlineKeyboardButton(text="🏠 Главное меню", callback_data="menu")],
            ]
        )
        await message.answer(format_kanji_card(k, is_fav, u_stat), reply_markup=kb)
        return

    kb_rows = [
        [InlineKeyboardButton(text=f"🏮 {k.char} — {k.meaning[:24]} ({k.level})", callback_data=f"card:{k.id}:ALL:0")]
        for k in found
    ]
    kb_rows.append([
        InlineKeyboardButton(text="🔍 Новый поиск", callback_data="search"),
        InlineKeyboardButton(text="🏠 Меню", callback_data="menu"),
    ])
    await message.answer(
        f"🔍 <b>Найдено по запросу «{html.escape(query)}»</b> ({len(found)}):",
        reply_markup=InlineKeyboardMarkup(inline_keyboard=kb_rows),
    )


